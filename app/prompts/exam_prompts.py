EXAM_PROMPTS = {
    "blood": LAB_PROMPT,
    "urine": LAB_PROMPT,
    "biochemistry": LAB_PROMPT,
    "sonography": SONOGRAPHY_PROMPT,
    "radiology": RADIOLOGY_PROMPT,
    "mri": MRI_PROMPT,
    "ct_scan": CT_SCAN_PROMPT,
    "mammography": MAMMOGRAPHY_PROMPT,
    "other": OTHER_PROMPT,
}


def get_prompt_template(exam_type: str) -> str:
    """
    Returns the specialized prompt template for the given exam_type,
    falling back to the generic lab prompt if the type is unknown.
    """
    return EXAM_PROMPTS.get(exam_type, LAB_PROMPT)